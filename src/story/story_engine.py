def load_used():

    if not os.path.exists(DATABASE):

        return []


    with open(
        DATABASE,
        "r",
        encoding="utf-8"
    ) as f:

        return json.load(f)




def save_used(data):

    os.makedirs(
        "src/story",
        exist_ok=True
    )


    with open(
        DATABASE,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            data,
            f,
            ensure_ascii=False,
            indent=2
        )




def create_story():


    used = load_used()


    available = [

        s for s in STORIES

        if s["title"] not in used

    ]


    # reset after all stories used

    if not available:

        used=[]

        available=STORIES



    story=random.choice(
        available
    )


    used.append(
        story["title"]
    )


    save_used(
        used
    )


    story["date"]=str(
        datetime.now()
    )


    print(
        "New Story:",
        story["title"]
    )


    return story
